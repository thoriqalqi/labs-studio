// pola untuk teks berisi angka / nama (t = penerjemah, untuk bagian yang perlu diterjemahkan juga)
export function buildPatterns(t) {
  return [
    [/^(\d+) menit lalu$/, '$1 min ago'],
    [/^(\d+) jam lalu$/, '$1 h ago'],
    [/^(\d+) hari lalu$/, '$1 days ago'],
    [/^(\d+) layer$/, (n) => `${n} layer${n === '1' ? '' : 's'}`],
    [/^(\d+) adegan$/, '$1 scenes'],
    [/^(\d+×\d+) · (\d+) fps · (\d+) layer$/, (s, f, n) => `${s} · ${f} fps · ${n} layer${n === '1' ? '' : 's'}`],
    [/^Pas (\d+)%$/, 'Fit $1%'],
    [/^(.+) · playhead di luar layer ini$/, (n) => `${t(n)} · playhead outside this layer`],
    [/^Mengunggah & menyiapkan video (.+)…$/, 'Uploading & preparing video $1…'],
    [/^Mengunggah (.+)…$/, 'Uploading $1…'],
    [/^(.+) tidak didukung$/, '$1 is not supported'],
    [/^(.+) ditambahkan \(([\d.]+) dtk, dengan audio\)$/, '$1 added ($2 s, with audio)'],
    [/^(.+) ditambahkan \(([\d.]+) dtk, tanpa audio\)$/, '$1 added ($2 s, no audio)'],
    [/^Voice over ditambahkan \(([\d.]+) dtk\)$/, 'Voice over added ($1 s)'],
    [/^(.+) ditambahkan \(([\d.]+) dtk\)$/, '$1 added ($2 s)'],
    [/^(Video|Audio|Voice over) lebih panjang dari komposisi\. Perpanjang komposisi jadi (\d+) detik\?$/,
      (k, n) => `The ${k === 'Voice over' ? 'voice over' : k.toLowerCase()} is longer than the composition. Extend the composition to ${n} seconds?`],
    [/^Gagal membaca (.+)$/, 'Could not read $1'],
    [/^Menyiapkan (.+)…$/, 'Preparing $1…'],
    [/^(.+) ditambahkan di ([\d.]+) dtk \(([\d.]+) dtk\)$/, '$1 added at $2 s ($3 s)'],
    [/^(.+) siap$/, '$1 ready'],
    [/^(Ekspor video|Ekspor audio|Simpan frame) gagal: ([\s\S]*)$/, (a, m) => `${t(a)} failed: ${m}`],
    [/^Video selesai: (.+)$/, 'Video done: $1'],
    [/^Audio selesai: (.+)$/, 'Audio done: $1'],
    [/^Frame tersimpan: (.+)$/, 'Frame saved: $1'],
    [/^Merender video (\d+)% · sisa ±(.+)$/, 'Rendering video $1% · about $2 left'],
    [/^Hapus "([\s\S]+)"\? File-nya dipindah ke folder \.trash dan masih bisa dipulihkan manual\.$/, 'Delete "$1"? The file moves to the .trash folder and can still be restored manually.'],
    [/^· (\d+) karakter$/, '· $1 characters'],
    [/^Sisa kuota ([\d.,]+) karakter$/, 'Quota left: $1 characters'],
    [/^Kalimat (\d+)$/, 'Line $1'],
    [/^Keyframe di ([\d.]+) detik$/, 'Keyframe at $1 seconds'],
    [/^([\d.]+) dtk$/, '$1 s'],
    [/^Merender layer (\d+)\/(\d+) untuk After Effects: (.+) (\d+)%$/, 'Rendering layer $1/$2 for After Effects: $3 $4%'],
    [/^After Effects siap: (.+)$/, 'After Effects ready: $1'],
    [/^Ekspor After Effects gagal: ([\s\S]*)$/, 'After Effects export failed: $1'],
    [/^(.+) · ([\d.]+) dtk$/, (p, n) => `${t(p)} · ${n} s`],
    [/^Keyframe ditambahkan \((\d+) properti\)$/, (n) => `Keyframe added (${n} propert${n === '1' ? 'y' : 'ies'})`],
    [/^(\d+) keyframe disalin$/, (n) => `${n} keyframe${n === '1' ? '' : 's'} copied`],
    [/^(\d+) keyframe ditempel, (\d+) dilewati$/, (n, m) => `${n} keyframe${n === '1' ? '' : 's'} pasted, ${m} skipped`],
    [/^(\d+) keyframe ditempel$/, (n) => `${n} keyframe${n === '1' ? '' : 's'} pasted`],
    [/^(\d+) keyframe dihapus$/, (n) => `${n} keyframe${n === '1' ? '' : 's'} deleted`],
    [/^SFX · (.+)$/, (x) => `SFX · ${t(x)}`],
    [/^Bola tanpa label$/, 'Orb (no label)'],
    [/^Bola (.+)$/, 'Orb $1'],
    [/^Daftar: (.+)$/, 'List: $1'],
    [/^Judul: (.+)$/, 'Title: $1']
  ];
}

